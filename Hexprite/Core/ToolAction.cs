namespace Hexprite.Core
{
    /// <summary>
    /// Represents the state of a tool action within an input event sequence.
    /// </summary>
    public enum ToolAction
    {
        /// <summary>Mouse/pointer button pressed.</summary>
        Down,
        /// <summary>Mouse/pointer moved.</summary>
        Move,
        /// <summary>Mouse/pointer button released.</summary>
        Up,
    }
}
