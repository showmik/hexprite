namespace Hexprite.Core
{
    /// <summary>
    /// Horizontal alignment for the Text tool relative to the click point.
    /// </summary>
    public enum TextToolAlignment
    {
        /// <summary>Text starts at the click point and grows rightward.</summary>
        Left,

        /// <summary>Text is centered on the click point.</summary>
        Center,

        /// <summary>Text ends at the click point and grows leftward.</summary>
        Right,
    }
}
