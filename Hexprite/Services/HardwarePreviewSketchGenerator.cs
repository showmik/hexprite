        public static string GenerateArduinoSketch(HardwarePreviewWiringConfig config, int baudRate)
        {
            var sb = new StringBuilder();
            sb.AppendLine("/*");
            sb.AppendLine("  HexpritePreview-Standalone-Arduino.ino");
            sb.AppendLine("  Generated by Hexprite for " + config.BoardPreset);
            sb.AppendLine("  Display: " + config.DisplayModel + " (" + config.InterfaceType + ")");
            sb.AppendLine("*/");
            sb.AppendLine();
            sb.AppendLine("#include <Arduino.h>");
            sb.AppendLine("#include <U8g2lib.h>");
            sb.AppendLine("#include <Wire.h>");
            sb.AppendLine();
            sb.AppendLine("// ═══════════════════════════════════════════════════════════════════════════════");
            sb.AppendLine("//  CONFIGURED HARDWARE PREVIEW SETTINGS");
            sb.AppendLine("// ═══════════════════════════════════════════════════════════════════════════════");
            sb.AppendLine();
            sb.AppendLine(CultureInfo.InvariantCulture, $"#define SERIAL_BAUD {baudRate}");
            sb.AppendLine();

            if (config.InterfaceType == "I2C")
            {
                sb.AppendLine("#define USE_I2C");
                sb.AppendLine(CultureInfo.InvariantCulture, $"#define I2C_SDA_PIN   {config.SdaPin.Trim()}");
                sb.AppendLine(CultureInfo.InvariantCulture, $"#define I2C_SCL_PIN   {config.SclPin.Trim()}");
                sb.AppendLine(CultureInfo.InvariantCulture, $"#define I2C_ADDRESS   {config.I2cAddress.Trim()}");
                if (config.UseSoftwareI2c)
                {
                    sb.AppendLine("#define USE_SOFTWARE_I2C");
                }
            }
            else
            {
                sb.AppendLine("#define USE_SPI");
                sb.AppendLine(CultureInfo.InvariantCulture, $"#define SPI_CS_PIN    {config.CsPin.Trim()}");
                sb.AppendLine(CultureInfo.InvariantCulture, $"#define SPI_DC_PIN    {config.DcPin.Trim()}");
                string rstPin = string.IsNullOrWhiteSpace(config.RstPin) ? "U8X8_PIN_NONE" : config.RstPin.Trim();
                sb.AppendLine(CultureInfo.InvariantCulture, $"#define SPI_RST_PIN   {rstPin}");
                sb.AppendLine(CultureInfo.InvariantCulture, $"#define SPI_CLK_PIN   {config.ClkPin.Trim()}");
                sb.AppendLine(CultureInfo.InvariantCulture, $"#define SPI_MOSI_PIN  {config.MosiPin.Trim()}");
            }

            sb.AppendLine();
            sb.AppendLine("// ═══════════════════════════════════════════════════════════════════════════════");
            sb.AppendLine("//  DISPLAY CONSTRUCTOR");
            sb.AppendLine("// ═══════════════════════════════════════════════════════════════════════════════");
            sb.AppendLine();
            sb.AppendLine(GetConstructorDeclaration(config));
            sb.AppendLine();
            sb.AppendLine("// ═══════════════════════════════════════════════════════════════════════════════");
            sb.AppendLine("//  PROTOCOL HANDLER & RUNTIME");
            sb.AppendLine("// ═══════════════════════════════════════════════════════════════════════════════");
            sb.AppendLine();
            sb.AppendLine("#if defined(ESP32) || defined(ESP8266) || defined(ARDUINO_ARCH_RP2040) || defined(ARDUINO_ARCH_STM32)");
            sb.AppendLine("  #define MAX_BUFFER 32800");
            sb.AppendLine("#elif defined(__AVR_ATmega2560__)");
            sb.AppendLine("  #define MAX_BUFFER 8200");
            sb.AppendLine("#elif defined(__AVR_ATmega328P__) || defined(__AVR_ATmega168__) || defined(ARDUINO_AVR_UNO) || defined(ARDUINO_AVR_NANO)");
            sb.AppendLine("  #define MAX_BUFFER 1040");
            sb.AppendLine("#else");
            sb.AppendLine("  #define MAX_BUFFER 4200");
            sb.AppendLine("#endif");
            sb.AppendLine("byte buffer[MAX_BUFFER];");
            sb.AppendLine("int bufferIndex = 0;");
            sb.AppendLine("bool packetStarted = false;");
            sb.AppendLine();
            sb.AppendLine("// Diagnostic response codes sent back to Hexprite");
            sb.AppendLine("#define HEXPRITE_ACK_OK         0xA5");
            sb.AppendLine("#define HEXPRITE_ERR_I2C_NACK   0xE1");
            sb.AppendLine("#define HEXPRITE_ERR_CHECKSUM   0xE2");
            sb.AppendLine();
            sb.AppendLine("void setup() {");
            sb.AppendLine("  Serial.begin(SERIAL_BAUD);");
            sb.AppendLine();

            if (config.InterfaceType == "I2C" && !config.UseSoftwareI2c)
            {
                sb.AppendLine("  #if defined(USE_I2C)");
                sb.AppendLine("    #if defined(__AVR__)");
                sb.AppendLine("      Wire.begin();");
                sb.AppendLine("    #elif defined(ESP32) || defined(ESP8266)");
                sb.AppendLine("      Wire.begin(I2C_SDA_PIN, I2C_SCL_PIN);");
                sb.AppendLine("    #elif defined(ARDUINO_ARCH_RP2040) || defined(ARDUINO_ARCH_STM32)");
                sb.AppendLine("      Wire.setSDA(I2C_SDA_PIN);");
                sb.AppendLine("      Wire.setSCL(I2C_SCL_PIN);");
                sb.AppendLine("      Wire.begin();");
                sb.AppendLine("    #else");
                sb.AppendLine("      Wire.begin();");
                sb.AppendLine("    #endif");
                sb.AppendLine();
                sb.AppendLine("    #if defined(WIRE_HAS_TIMEOUT)");
                sb.AppendLine("      Wire.setWireTimeout(25000, true); // 25ms timeout, reset bus on hang");
                sb.AppendLine("    #endif");
                sb.AppendLine("  #endif");
            }

            sb.AppendLine();
            sb.AppendLine("  u8g2.begin();");
            sb.AppendLine("  u8g2.clearBuffer();");
            sb.AppendLine("  u8g2.setFont(u8g2_font_6x10_tf);");
            sb.AppendLine("  u8g2.drawStr(0, 10, \"Hexprite Live\");");
            sb.AppendLine("  u8g2.drawStr(0, 25, \"Waiting for data...\");");
            sb.AppendLine("  u8g2.sendBuffer();");
            sb.AppendLine("}");
            sb.AppendLine();
            sb.AppendLine("void loop() {");
            sb.AppendLine("  while (Serial.available()) {");
            sb.AppendLine("    byte b = Serial.read();");
            sb.AppendLine("    if (!packetStarted) {");
            sb.AppendLine("      if (bufferIndex == 0 && b == 0xAA) {");
            sb.AppendLine("        buffer[bufferIndex++] = b;");
            sb.AppendLine("      } else if (bufferIndex == 1 && b == 0x55) {");
            sb.AppendLine("        buffer[bufferIndex++] = b;");
            sb.AppendLine("        packetStarted = true;");
            sb.AppendLine("      } else {");
            sb.AppendLine("        bufferIndex = (b == 0xAA) ? 1 : 0;");
            sb.AppendLine("        if (bufferIndex == 1) buffer[0] = 0xAA;");
            sb.AppendLine("      }");
            sb.AppendLine("      continue;");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine("    if (bufferIndex >= MAX_BUFFER) {");
            sb.AppendLine("      packetStarted = false;");
            sb.AppendLine("      bufferIndex = 0;");
            sb.AppendLine("      continue;");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine("    buffer[bufferIndex++] = b;");
            sb.AppendLine("    if (bufferIndex >= 6) {");
            sb.AppendLine("      uint16_t w = buffer[2] | (buffer[3] << 8);");
            sb.AppendLine("      uint16_t h = buffer[4] | (buffer[5] << 8);");
            sb.AppendLine("      uint16_t dataSize = ((w + 7) / 8) * h;");
            sb.AppendLine("      uint16_t totalPacketSize = 6 + dataSize + 1;");
            sb.AppendLine();
            sb.AppendLine("      if (totalPacketSize > MAX_BUFFER) {");
            sb.AppendLine("        packetStarted = false;");
            sb.AppendLine("        bufferIndex = 0;");
            sb.AppendLine("        continue;");
            sb.AppendLine("      }");
            sb.AppendLine();
            sb.AppendLine("      if (bufferIndex == totalPacketSize) {");
            sb.AppendLine("        byte calculatedXor = 0;");
            sb.AppendLine("        for (int i = 0; i < totalPacketSize - 1; i++) {");
            sb.AppendLine("          calculatedXor ^= buffer[i];");
            sb.AppendLine("        }");
            sb.AppendLine("        byte receivedXor = buffer[totalPacketSize - 1];");
            sb.AppendLine();
            sb.AppendLine("        if (calculatedXor == receivedXor) {");
            sb.AppendLine("          #if defined(USE_I2C) && !defined(USE_SOFTWARE_I2C)");
            sb.AppendLine("            Wire.beginTransmission(I2C_ADDRESS);");
            sb.AppendLine("            if (Wire.endTransmission() != 0) {");
            sb.AppendLine("              Serial.write(HEXPRITE_ERR_I2C_NACK);");
            sb.AppendLine("              Serial.flush();");
            sb.AppendLine("              packetStarted = false;");
            sb.AppendLine("              bufferIndex = 0;");
            sb.AppendLine("              continue;");
            sb.AppendLine("            }");
            sb.AppendLine("          #endif");
            sb.AppendLine();
            sb.AppendLine("          u8g2.clearBuffer();");
            sb.AppendLine("          u8g2.drawXBM(0, 0, w, h, &buffer[6]);");
            sb.AppendLine("          u8g2.sendBuffer();");
            sb.AppendLine("          Serial.write(HEXPRITE_ACK_OK);");
            sb.AppendLine("          Serial.flush();");
            sb.AppendLine("        } else {");
            sb.AppendLine("          Serial.write(HEXPRITE_ERR_CHECKSUM);");
            sb.AppendLine("          Serial.flush();");
            sb.AppendLine("        }");
            sb.AppendLine("        packetStarted = false;");
            sb.AppendLine("        bufferIndex = 0;");
            sb.AppendLine("      }");
            sb.AppendLine("    }");
            sb.AppendLine("  }");
            sb.AppendLine("}");

            return sb.ToString();
        }

        public static string GetConstructorDeclaration(HardwarePreviewWiringConfig config)
        {
            string model = config.DisplayModel;
            bool isI2c = config.InterfaceType == "I2C";
            bool isSwI2c = isI2c && config.UseSoftwareI2c;

            if (isI2c)
            {
                if (isSwI2c)
                {
                    return model switch
                    {
                        "SSD1306 128x32" =>
                            $"U8G2_SSD1306_128X32_UNIVISION_F_SW_I2C u8g2(U8G2_R0, /* clock=*/ {config.SclPin}, /* data=*/ {config.SdaPin}, /* reset=*/ U8X8_PIN_NONE);",
                        "SH1106 128x64" =>
                            $"U8G2_SH1106_128X64_NONAME_F_SW_I2C u8g2(U8G2_R0, /* clock=*/ {config.SclPin}, /* data=*/ {config.SdaPin}, /* reset=*/ U8X8_PIN_NONE);",
                        "SSD1309 128x64" =>
                            $"U8G2_SSD1309_128X64_NONAME0_F_SW_I2C u8g2(U8G2_R0, /* clock=*/ {config.SclPin}, /* data=*/ {config.SdaPin}, /* reset=*/ U8X8_PIN_NONE);",
                        _ =>
                            $"U8G2_SSD1306_128X64_NONAME_F_SW_I2C u8g2(U8G2_R0, /* clock=*/ {config.SclPin}, /* data=*/ {config.SdaPin}, /* reset=*/ U8X8_PIN_NONE);"
                    };
                }
                else
                {
                    return model switch
                    {
                        "SSD1306 128x32" =>
                            "U8G2_SSD1306_128X32_UNIVISION_F_HW_I2C u8g2(U8G2_R0, /* reset=*/ U8X8_PIN_NONE);",
                        "SH1106 128x64" =>
                            "U8G2_SH1106_128X64_NONAME_F_HW_I2C u8g2(U8G2_R0, /* reset=*/ U8X8_PIN_NONE);",
                        "SSD1309 128x64" =>
                            "U8G2_SSD1309_128X64_NONAME0_F_HW_I2C u8g2(U8G2_R0, /* reset=*/ U8X8_PIN_NONE);",
                        _ =>
                            "U8G2_SSD1306_128X64_NONAME_F_HW_I2C u8g2(U8G2_R0, /* reset=*/ U8X8_PIN_NONE);"
                    };
                }
            }
            else // SPI
            {
                string rst = string.IsNullOrWhiteSpace(config.RstPin) ? "U8X8_PIN_NONE" : config.RstPin;
                return model switch
                {
                    "SSD1306 128x32" =>
                        $"U8G2_SSD1306_128X32_UNIVISION_F_4W_HW_SPI u8g2(U8G2_R0, /* cs=*/ {config.CsPin}, /* dc=*/ {config.DcPin}, /* reset=*/ {rst});",
                    "SH1106 128x64" =>
                        $"U8G2_SH1106_128X64_NONAME_F_4W_HW_SPI u8g2(U8G2_R0, /* cs=*/ {config.CsPin}, /* dc=*/ {config.DcPin}, /* reset=*/ {rst});",
                    "SSD1309 128x64" =>
                        $"U8G2_SSD1309_128X64_NONAME0_F_4W_HW_SPI u8g2(U8G2_R0, /* cs=*/ {config.CsPin}, /* dc=*/ {config.DcPin}, /* reset=*/ {rst});",
                    "ST7920 128x64" =>
                        $"U8G2_ST7920_128X64_F_HW_SPI u8g2(U8G2_R0, /* cs=*/ {config.CsPin}, /* reset=*/ {rst});",
                    _ =>
                        $"U8G2_SSD1306_128X64_NONAME_F_4W_HW_SPI u8g2(U8G2_R0, /* cs=*/ {config.CsPin}, /* dc=*/ {config.DcPin}, /* reset=*/ {rst});"
                };
            }
        }

