            sb.AppendLine("  hexpritePreview.update(); // Checks for live serial frames from Hexprite");
            sb.AppendLine("  // ... your project code ...");
            sb.AppendLine("}");
            return sb.ToString();
        }

        public static List<WirePinMapping> GetWireMapping(HardwarePreviewWiringConfig config)
        {
            var list = new List<WirePinMapping>();

            if (config.InterfaceType == "I2C")
            {
                list.Add(new WirePinMapping { DisplayPin = "VCC", BoardPin = "3.3V / 5V", Description = "Power supply", WireColor = "Red" });
                list.Add(new WirePinMapping { DisplayPin = "GND", BoardPin = "GND", Description = "Ground reference", WireColor = "DimGray" });
                list.Add(new WirePinMapping { DisplayPin = "SDA / D1", BoardPin = config.SdaPin, Description = "Serial Data Line", WireColor = "Gold" });
                list.Add(new WirePinMapping { DisplayPin = "SCL / D0", BoardPin = config.SclPin, Description = "Serial Clock Line", WireColor = "DeepSkyBlue" });
            }
            else // SPI
            {
                list.Add(new WirePinMapping { DisplayPin = "VCC", BoardPin = "3.3V / 5V", Description = "Power supply", WireColor = "Red" });
                list.Add(new WirePinMapping { DisplayPin = "GND", BoardPin = "GND", Description = "Ground reference", WireColor = "DimGray" });
                list.Add(new WirePinMapping { DisplayPin = "CS", BoardPin = config.CsPin, Description = "Chip Select", WireColor = "Orange" });
                list.Add(new WirePinMapping { DisplayPin = "DC", BoardPin = config.DcPin, Description = "Data / Command control", WireColor = "LimeGreen" });
                list.Add(new WirePinMapping { DisplayPin = "RST", BoardPin = string.IsNullOrWhiteSpace(config.RstPin) ? "None (or 3.3V)" : config.RstPin, Description = "Reset line", WireColor = "White" });
                list.Add(new WirePinMapping { DisplayPin = "D0 / SCK", BoardPin = config.ClkPin, Description = "SPI Clock", WireColor = "DeepSkyBlue" });
                list.Add(new WirePinMapping { DisplayPin = "D1 / MOSI", BoardPin = config.MosiPin, Description = "SPI Master-Out-Slave-In", WireColor = "Gold" });
            }

            return list;
        }

        public static bool UpdateStandaloneSketchInAppData(HardwarePreviewWiringConfig config, int baudRate)
        {
            try
            {
                // Always write to the user's AppData directory (writable), not the install directory.
                string standaloneDir = Path.Combine(AssetsPathService.AppDataAssetsDirectory, AssetsPathService.HexpritePreviewStandaloneFolderName);

                if (!Directory.Exists(standaloneDir))
                {
                    Directory.CreateDirectory(standaloneDir);
                }

                string targetFile = Path.Combine(standaloneDir, AssetsPathService.StandaloneSketchFileName);
                string sketch = GenerateArduinoSketch(config, baudRate);
                SafeFileIo.WriteAllTextAtomic(targetFile, sketch, maxRetries: 3);
                return true;
            }
            catch (Exception ex)
            {
                Log.Warning(ex, "Failed to update standalone sketch in AppData");
                return false;
            }
        }

        public static string GeneratePlatformIOConfig(HardwarePreviewWiringConfig config, int baudRate)
        {
            var sb = new StringBuilder();
            sb.AppendLine("/*");
            sb.AppendLine(" * config.h — Hexprite Live Hardware Preview Configuration");
            sb.AppendLine(" * Generated by Hexprite for " + config.BoardPreset);
            sb.AppendLine(" */");
            sb.AppendLine();
            sb.AppendLine("#pragma once");
            sb.AppendLine();
            sb.AppendLine(CultureInfo.InvariantCulture, $"#define SERIAL_BAUD {baudRate}");
            sb.AppendLine();
            if (config.InterfaceType == "I2C")
            {
                sb.AppendLine("#define USE_I2C");
                sb.AppendLine("// #define USE_SPI");
            }
            else
            {
                sb.AppendLine("// #define USE_I2C");
                sb.AppendLine("#define USE_SPI");
            }
            sb.AppendLine();
            sb.AppendLine("// I2C Configuration");
            sb.AppendLine(CultureInfo.InvariantCulture, $"#define I2C_SDA_PIN   {config.SdaPin.Trim()}");
            sb.AppendLine(CultureInfo.InvariantCulture, $"#define I2C_SCL_PIN   {config.SclPin.Trim()}");
            sb.AppendLine(CultureInfo.InvariantCulture, $"#define I2C_ADDRESS   {config.I2cAddress.Trim()}");
            if (config.UseSoftwareI2c)
            {
                sb.AppendLine("#define USE_SOFTWARE_I2C");
            }
            sb.AppendLine();
            sb.AppendLine("// SPI Configuration");
            sb.AppendLine(CultureInfo.InvariantCulture, $"#define SPI_CS_PIN    {config.CsPin.Trim()}");
            sb.AppendLine(CultureInfo.InvariantCulture, $"#define SPI_DC_PIN    {config.DcPin.Trim()}");
            sb.AppendLine(CultureInfo.InvariantCulture, $"#define SPI_RST_PIN   {(string.IsNullOrWhiteSpace(config.RstPin) ? "U8X8_PIN_NONE" : config.RstPin.Trim())}");
            sb.AppendLine(CultureInfo.InvariantCulture, $"#define SPI_CLK_PIN   {config.ClkPin.Trim()}");
            sb.AppendLine(CultureInfo.InvariantCulture, $"#define SPI_MOSI_PIN  {config.MosiPin.Trim()}");
            sb.AppendLine();
            sb.AppendLine("// Display Model");
            string defineName = GetPlatformIODisplayDefine(config.DisplayModel, config.InterfaceType);
            sb.AppendLine(CultureInfo.InvariantCulture, $"#define {defineName}");
            sb.AppendLine();
            return sb.ToString();
        }

        private static string GetPlatformIODisplayDefine(string displayModel, string interfaceType)
        {
            string suffix = interfaceType == "SPI" ? "SPI" : "I2C";
            return displayModel switch
            {
                "SSD1306 128x32" => $"DISPLAY_SSD1306_128X32_{suffix}",
                "SH1106 128x64" => $"DISPLAY_SH1106_128X64_{suffix}",
                "SSD1309 128x64" => $"DISPLAY_SSD1309_128X64_{suffix}",
                "ST7920 128x64" => "DISPLAY_ST7920_128X64_SPI",
                _ => $"DISPLAY_SSD1306_128X64_{suffix}"
            };
        }

