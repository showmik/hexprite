        {
            var sb = new StringBuilder();
            sb.AppendLine("// === Hexprite Live Hardware Preview Integration ===");
            sb.AppendLine("#include <U8g2lib.h>");
            if (config.InterfaceType == "I2C") sb.AppendLine("#include <Wire.h>");
            sb.AppendLine("#include <HexpritePreview.h>");
            sb.AppendLine();
            sb.AppendLine("// 1. Display constructor for " + config.DisplayModel + ":");
