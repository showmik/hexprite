        public static bool UpdatePlatformIOConfigInAppData(HardwarePreviewWiringConfig config, int baudRate)
        {
            try
            {
                string pioRoot = Path.Combine(AssetsPathService.AppDataAssetsDirectory, AssetsPathService.HexpritePreviewPlatformIOFolderName);
                string pioSrc = Path.Combine(pioRoot, "src");
                Directory.CreateDirectory(pioSrc);

                string cfgFile = Path.Combine(pioSrc, "config.h");
                string cfgContent = GeneratePlatformIOConfig(config, baudRate);
                SafeFileIo.WriteAllTextAtomic(cfgFile, cfgContent, maxRetries: 3);

                string iniFile = Path.Combine(pioRoot, "platformio.ini");
                string iniContent = GeneratePlatformIOIni(config.BoardPreset, baudRate);
                SafeFileIo.WriteAllTextAtomic(iniFile, iniContent, maxRetries: 3);

                return true;
            }
            catch (Exception ex)
            {
                Log.Warning(ex, "Failed to update PlatformIO config in AppData");
                return false;
            }
        }
    }
