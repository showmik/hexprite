    // ── 2. Multi-Sprite File Isolation ───────────────────────────────────

    [Fact]
    public void ExtractSprites_MultiSpriteFile_MaintainsStrictIsolation()
    {
        string code = """
            // 1. Tile with explicit macros
            #define TILE_WIDTH 16
            #define TILE_HEIGHT 16
            const uint8_t PROGMEM tile_grass[32] = {
                0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
                0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E, 0x0F,
                0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17,
                0x18, 0x19, 0x1A, 0x1B, 0x1C, 0x1D, 0x1E, 0x1F
            };

            // 2. Palette table that should NOT be picked up as a sprite
            const unsigned long palette[4] = {
                0x000000, 0xFFFFFF, 0xFF0000, 0x00FF00
            };

            // 3. Bare 8x8 sprite that should NOT adopt TILE_WIDTH 16
            const uint8_t PROGMEM hero_icon[8] = {
                0x3C,
                0x42,
                0x81,
                0x99,
                0x99,
                0x81,
                0x42,
                0x3C
            };

            // 4. Bare 24x8 wide sprite
            const uint8_t PROGMEM banner_bar[24] = {
                0x01, 0x02, 0x03,
                0x04, 0x05, 0x06,
                0x07, 0x08, 0x09,
                0x0A, 0x0B, 0x0C,
                0x0D, 0x0E, 0x0F,
                0x10, 0x11, 0x12,
                0x13, 0x14, 0x15,
                0x16, 0x17, 0x18
            };
            """;
        string path = WriteTempFile("multi_sprite_isolation.c", code);

        var sprites = _fileSvc.ExtractSpritesFromFile(path);

        Assert.Equal(3, sprites.Count);

        var tile = sprites.Find(s => s.Name == "tile_grass");
        Assert.NotNull(tile);
        Assert.Equal(16, tile.Width);
        Assert.Equal(16, tile.Height);

        var hero = sprites.Find(s => s.Name == "hero_icon");
        Assert.NotNull(hero);
        Assert.Equal(8, hero.Width);
        Assert.Equal(8, hero.Height);

        var banner = sprites.Find(s => s.Name == "banner_bar");
        Assert.NotNull(banner);
        Assert.Equal(24, banner.Width);
        Assert.Equal(8, banner.Height);
    }

