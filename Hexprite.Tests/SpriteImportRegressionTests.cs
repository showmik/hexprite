    // ── 4. UI Dialog Paste Sequence State Machine (WPF STA) ──────────────

    [Fact]
    public void ImportFromCodeDialog_SequentialPastes_CleanlyTransitionsState()
    {
        WpfTestHelper.RunOnSta(() =>
        {
            var dlg = new ImportFromCodeDialog();

            // 1. Explicit 8x8 define
            dlg.TxtCode.Text = """
                #define ICON_WIDTH 8
                #define ICON_HEIGHT 8
                const uint8_t icon[8] = { 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08 };
                """;
            Assert.Equal("8", dlg.TxtWidth.Text);
            Assert.Equal("8", dlg.TxtHeight.Text);
            Assert.Contains("auto-detected", dlg.TxtDetectionHint.Text);

            // 2. Replace with bare 24x8 sprite (no #define) -> Must NOT stay stuck at 8x8!
            dlg.TxtCode.Text = """
                const uint8_t PROGMEM spr_banner[24] = {
                    0x01, 0x02, 0x03,
                    0x04, 0x05, 0x06,
                    0x07, 0x08, 0x09,
                    0x0A, 0x0B, 0x0C,
                    0x0D, 0x0E, 0x0F,
                    0x10, 0x11, 0x12,
                    0x13, 0x14, 0x15,
                    0x16, 0x17, 0x18
                };
                """;
            // 3 bytes per row = 24px width, 8 rows = 8px height -> 24x8
            Assert.Equal("24", dlg.TxtWidth.Text);
            Assert.Equal("8", dlg.TxtHeight.Text);

            // 3. Clear text
            dlg.TxtCode.Text = "";
            Assert.Equal("", dlg.TxtDetectionHint.Text);

            // 4. Paste 16x16 explicit
            dlg.TxtCode.Text = """
                #define TILE_W 16
                #define TILE_H 16
                const uint8_t tile[32] = { 0 };
                """;
            Assert.Equal("16", dlg.TxtWidth.Text);
            Assert.Equal("16", dlg.TxtHeight.Text);
        });
    }
