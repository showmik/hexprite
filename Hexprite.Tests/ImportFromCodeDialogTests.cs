        [Fact]
        public void ImportFromCodeDialog_WhenMultiFrameAnimationPasted_DetectsAllFramesAndAllowsNavigation()
        {
            WpfTestHelper.RunOnSta(() =>
            {
                var dlg = new ImportFromCodeDialog();
                const string code = @"
#define FRAME_SIZE 8

// 3 Frames of an alternating 8x8 flashing brick animation (1-bit)
const unsigned char block_animation[3][FRAME_SIZE] = {
    // Frame 0: Border outline
    { 0xFF, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0xFF },
    
    // Frame 1: Cross hatch pattern
    { 0xAA, 0x55, 0xAA, 0x55, 0xAA, 0x55, 0xAA, 0x55 },
    
    // Frame 2: Solid square
    { 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF }
};";

                dlg.TxtCode.Text = code;

                Assert.Equal("8", dlg.TxtWidth.Text);
                Assert.Equal("8", dlg.TxtHeight.Text);
                Assert.Contains("3 animation frames", dlg.TxtStats.Text);
                Assert.Contains("3 frames", dlg.TxtPreviewDimBadge.Text);
                Assert.Equal(System.Windows.Visibility.Visible, dlg.BorderFrameNav.Visibility);
                Assert.Equal("Frame 1 of 3", dlg.TxtFrameNavIndicator.Text);

                // Click Next Frame
                dlg.BtnNextFrame.RaiseEvent(new System.Windows.RoutedEventArgs(System.Windows.Controls.Primitives.ButtonBase.ClickEvent));
                Assert.Equal("Frame 2 of 3", dlg.TxtFrameNavIndicator.Text);

                // Click Next Frame again
                dlg.BtnNextFrame.RaiseEvent(new System.Windows.RoutedEventArgs(System.Windows.Controls.Primitives.ButtonBase.ClickEvent));
                Assert.Equal("Frame 3 of 3", dlg.TxtFrameNavIndicator.Text);

                // Click Prev Frame
                dlg.BtnPrevFrame.RaiseEvent(new System.Windows.RoutedEventArgs(System.Windows.Controls.Primitives.ButtonBase.ClickEvent));
                Assert.Equal("Frame 2 of 3", dlg.TxtFrameNavIndicator.Text);

                // Assert Vector Paths are present
                Assert.IsType<System.Windows.Shapes.Path>(dlg.BtnPrevFrame.Content);
                Assert.IsType<System.Windows.Shapes.Path>(dlg.BtnNextFrame.Content);
                Assert.NotNull(dlg.IconPlayPause);

                // Click Play
                dlg.BtnPlayAnimation.RaiseEvent(new System.Windows.RoutedEventArgs(System.Windows.Controls.Primitives.ButtonBase.ClickEvent));
                Assert.Same(ImportFromCodeDialog.PauseGeometry, dlg.IconPlayPause.Data);

                // Click Pause
                dlg.BtnPlayAnimation.RaiseEvent(new System.Windows.RoutedEventArgs(System.Windows.Controls.Primitives.ButtonBase.ClickEvent));
                Assert.Same(ImportFromCodeDialog.PlayGeometry, dlg.IconPlayPause.Data);
            });
        }

